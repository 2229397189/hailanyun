
CREATE TABLE IF NOT EXISTS nodes (
  id          VARCHAR(32) PRIMARY KEY,
  hostname    VARCHAR(64)  NOT NULL,
  ip          VARCHAR(64)  NOT NULL,
  status      VARCHAR(16)  NOT NULL,   -- Ready / NotReady / Cordoned / Draining
  role        VARCHAR(16)  NOT NULL,   -- server / agent
  cpu_cores   INT          NOT NULL,
  mem_gb      INT          NOT NULL,
  disk_gb     INT          NOT NULL,
  k8s_version VARCHAR(32)  NOT NULL,
  pod_count   INT          NOT NULL,
  gpu_count   INT          NOT NULL,
  pool_id     VARCHAR(32)  NOT NULL,
  labels      VARCHAR(256),
  taints      VARCHAR(256)
);

CREATE TABLE IF NOT EXISTS gpus (
  id          VARCHAR(32) PRIMARY KEY,
  node_id     VARCHAR(32) NOT NULL,
  idx         INT         NOT NULL,
  model       VARCHAR(64) NOT NULL,
  mem_gb      INT         NOT NULL,
  status      VARCHAR(16) NOT NULL,   -- free / occupied / fault / reserved
  instance_id VARCHAR(32),
  util_pct    INT         DEFAULT 0,
  temp_c      INT         DEFAULT 45,
  power_w     INT         DEFAULT 0,
  CONSTRAINT uk_gpu_node_idx UNIQUE (node_id, idx)
);

CREATE TABLE IF NOT EXISTS users (
  id           VARCHAR(32) PRIMARY KEY,
  username     VARCHAR(64) NOT NULL,
  display_name VARCHAR(64) NOT NULL,
  role         VARCHAR(16) NOT NULL,   -- admin / ops / tenant
  tenant_id    VARCHAR(32),
  password_hash VARCHAR(100),
  status       VARCHAR(16) NOT NULL DEFAULT 'active',   -- active / disabled
  fail_count   INT DEFAULT 0,
  locked_until TIMESTAMP,
  last_login_at TIMESTAMP,
  CONSTRAINT uk_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS sessions (
  id         VARCHAR(64) PRIMARY KEY,   -- Bearer token
  user_id    VARCHAR(32) NOT NULL,
  username   VARCHAR(64) NOT NULL,
  role       VARCHAR(16) NOT NULL,
  tenant_id  VARCHAR(32),
  ip         VARCHAR(64),
  user_agent VARCHAR(200),
  created_at TIMESTAMP NOT NULL,
  last_seen  TIMESTAMP NOT NULL,
  expire_at  TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS tenants (
  id           VARCHAR(32) PRIMARY KEY,
  name         VARCHAR(64)   NOT NULL,
  quota_gpus   INT           NOT NULL,
  balance_yuan DECIMAL(12,2) NOT NULL,
  status       VARCHAR(16)   NOT NULL,  -- active / frozen
  owner        VARCHAR(64),
  created_at   TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
  id              VARCHAR(32) PRIMARY KEY,
  order_no        VARCHAR(64) NOT NULL,
  tenant_id       VARCHAR(32) NOT NULL,
  sku             VARCHAR(32) NOT NULL,
  gpu_count       INT         NOT NULL,
  hours           INT         NOT NULL,
  unit_price      DECIMAL(10,2) NOT NULL,
  amount          DECIMAL(12,2) NOT NULL,
  status          VARCHAR(16) NOT NULL,
  created_at      TIMESTAMP   NOT NULL,
  CONSTRAINT uk_order_no UNIQUE (order_no)
);

CREATE TABLE IF NOT EXISTS instances (
  id           VARCHAR(32) PRIMARY KEY,
  order_id     VARCHAR(32) NOT NULL,
  tenant_id    VARCHAR(32) NOT NULL,
  node_id      VARCHAR(32),
  gpu_ids      VARCHAR(128),
  gpu_count    INT         NOT NULL,
  pod_name     VARCHAR(64),
  status       VARCHAR(20) NOT NULL,
  created_at   TIMESTAMP   NOT NULL,
  started_at   TIMESTAMP,
  expire_at    TIMESTAMP   NOT NULL,
  used_seconds BIGINT      DEFAULT 0,
  released_at  TIMESTAMP
);

CREATE TABLE IF NOT EXISTS billing_records (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id VARCHAR(32) NOT NULL,
  tenant_id   VARCHAR(32) NOT NULL,
  gpu_count   INT          NOT NULL,
  seconds     BIGINT       NOT NULL,
  unit_price  DECIMAL(10,2) NOT NULL,
  amount      DECIMAL(12,2) NOT NULL,
  settled_at  TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS pools (
  id          VARCHAR(32) PRIMARY KEY,
  name        VARCHAR(64) NOT NULL,
  policy      VARCHAR(32) NOT NULL,   -- binpack / spread
  description VARCHAR(128)
);

CREATE TABLE IF NOT EXISTS queues (
  id        VARCHAR(32) PRIMARY KEY,
  pool_id   VARCHAR(32) NOT NULL,
  name      VARCHAR(64) NOT NULL,
  gpu_quota INT         NOT NULL,
  weight    INT         NOT NULL,
  priority  INT         NOT NULL
);

CREATE TABLE IF NOT EXISTS alerts (
  id         VARCHAR(32) PRIMARY KEY,
  level      VARCHAR(8)  NOT NULL,   -- P0 / P1 / P2
  title      VARCHAR(128) NOT NULL,
  source     VARCHAR(32) NOT NULL,   -- node / gpu / tenant / platform
  target     VARCHAR(64) NOT NULL,
  status     VARCHAR(16) NOT NULL,   -- active / acked / resolved
  detail     VARCHAR(256),
  created_at TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS inspections (
  id           VARCHAR(32) PRIMARY KEY,
  run_at       TIMESTAMP   NOT NULL,
  health_score INT         NOT NULL,
  total_issues INT         NOT NULL,
  summary      VARCHAR(256)
);

CREATE TABLE IF NOT EXISTS inspection_items (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspection_id VARCHAR(32) NOT NULL,
  level         VARCHAR(8)  NOT NULL,
  item          VARCHAR(128) NOT NULL,
  target        VARCHAR(64) NOT NULL,
  suggestion    VARCHAR(256) NOT NULL,
  fixed         BOOLEAN     NOT NULL
);

CREATE TABLE IF NOT EXISTS workloads (
  id          VARCHAR(32) PRIMARY KEY,
  name        VARCHAR(64) NOT NULL,
  kind        VARCHAR(16) NOT NULL,      -- Deployment / StatefulSet / Job
  namespace   VARCHAR(64) NOT NULL,
  image       VARCHAR(160) NOT NULL,
  gpu_count   INT         NOT NULL,
  mem_limit   VARCHAR(16) NOT NULL,      -- whole / half / quarter
  policy      VARCHAR(16) NOT NULL,      -- binpack / spread / gang
  status      VARCHAR(16) NOT NULL,      -- Pending / Running / Failed
  tenant_id   VARCHAR(32),
  created_at  TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS resources (
  id          VARCHAR(32) PRIMARY KEY,
  api_version VARCHAR(32) NOT NULL,
  kind        VARCHAR(32) NOT NULL,
  namespace   VARCHAR(64) NOT NULL,
  name        VARCHAR(64) NOT NULL,
  yaml_text   TEXT        NOT NULL,
  created_at  TIMESTAMP   NOT NULL,
  CONSTRAINT uk_res UNIQUE (kind, namespace, name)
);

CREATE TABLE IF NOT EXISTS alert_rules (
  id      VARCHAR(32) PRIMARY KEY,
  name    VARCHAR(64)  NOT NULL,
  target  VARCHAR(32)  NOT NULL,
  expr    VARCHAR(160) NOT NULL,
  level   VARCHAR(8)   NOT NULL,
  notify  VARCHAR(64)  NOT NULL,
  enabled BOOLEAN      NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  k    VARCHAR(64) PRIMARY KEY,
  v    VARCHAR(256) NOT NULL,
  note VARCHAR(128)
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor      VARCHAR(32)  NOT NULL,
  action     VARCHAR(64)  NOT NULL,
  target     VARCHAR(64)  NOT NULL,
  detail     VARCHAR(256),
  created_at TIMESTAMP    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_gpus_status ON gpus(status);
CREATE INDEX IF NOT EXISTS idx_inst_status ON instances(status);
CREATE INDEX IF NOT EXISTS idx_bill_tenant ON billing_records(tenant_id);
CREATE INDEX IF NOT EXISTS idx_alert_status ON alerts(status);
